# This script calculates Fst values for samples within the Q. tardifolia Texas red oak dataset. 
# It does this using the dartR function gl.fst.pop, which generates a matrix of distances between populations 
# and a matrix of p values. The function takes a genlight object as the main argument; this genlight object is 
# built from a genind object, which was generated using the Stacks populations module. 

# The following species are used as "populations", for the purpose of this calculation: gravesii, hypoleucoides,
# tardifolia and other known hybrids, and emoryi.

library(dartR)

# Specify the filepath to the Stacks populations directory for the Clust 3 FstCalcs dataset
FstCalcs_Dir <- 
  '/RAID1/QUTA_TX_RedOaks/Genotyping/SNP_Calling/Output/All_seReadsOnly/FstCalcs/'
FstCalcs_popmap <- 
  '/RAID1/QUTA_TX_RedOaks/Genotyping/SNP_Calling/Popmaps/QUTA_All_FstCalcs_popmap'
